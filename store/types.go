// FormatETag formats a positive integer resource version as a weak HTTP ETag per FHIR R4 (e.g., W/"1").
func FormatETag(version int) string {
	return fmt.Sprintf(`W/"%d"`, version)
}

// ParseETagVersion parses an HTTP ETag or If-Match header (e.g., W/"3", "3", or 3) into a positive version integer.
func ParseETagVersion(etag string) (int, error) {
	s := strings.TrimSpace(etag)
	if s == "" {
		return 0, fmt.Errorf("%w: empty value", ErrInvalidETag)
	}
	if strings.HasPrefix(s, "W/") || strings.HasPrefix(s, "w/") {
		s = strings.TrimSpace(s[2:])
		if len(s) < 2 || !strings.HasPrefix(s, `"`) || !strings.HasSuffix(s, `"`) {
			return 0, fmt.Errorf("%w: %q", ErrInvalidETag, etag)
		}
		s = s[1 : len(s)-1]
	} else if strings.HasPrefix(s, `"`) || strings.HasSuffix(s, `"`) {
		if len(s) < 2 || !strings.HasPrefix(s, `"`) || !strings.HasSuffix(s, `"`) {
			return 0, fmt.Errorf("%w: %q", ErrInvalidETag, etag)
		}
		s = s[1 : len(s)-1]
	}
	v, err := strconv.Atoi(s)
	if err != nil || v <= 0 {
		return 0, fmt.Errorf("%w: %q", ErrInvalidETag, etag)
	}
	return v, nil
}

// CanonicalCompartmentType returns the canonical HL7 FHIR R4 compartment resource type
// ("Patient", "Encounter", "Practitioner", "RelatedPerson", or "Device"), or "" if s is not a compartment type.
func CanonicalCompartmentType(s string) string {
	switch strings.ToLower(strings.TrimSpace(s)) {
	case "patient":
		return "Patient"
	case "encounter":
		return "Encounter"
	case "practitioner":
		return "Practitioner"
	case "relatedperson":
		return "RelatedPerson"
	case "device":
		return "Device"
	default:
		return ""
	}
}

// IsCompartmentType returns true if s is one of the 5 HL7 FHIR R4 compartment types
// (Patient, Encounter, Practitioner, RelatedPerson, Device).
func IsCompartmentType(s string) bool {
	return CanonicalCompartmentType(s) != ""
}

